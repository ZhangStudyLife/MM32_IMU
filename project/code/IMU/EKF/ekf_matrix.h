#ifndef _EKF_MATRIX_H
#define _EKF_MATRIX_H

#include <stdint.h>
#include <stdbool.h>

/********************************************************************************************************************
 * 矩阵维度配置
 ********************************************************************************************************************/

// EKF状态维度（四元数4 + 陀螺仪零漂3 = 7维）
#define EKF_STATE_DIM       (7)

// 最大矩阵维度（用于静态分配）
#define MATRIX_MAX_DIM      (7)

// 观测维度（加速度计3 + 磁力计3 = 6维）
#define EKF_MEAS_DIM        (6)

/********************************************************************************************************************
 * 矩阵数据结构
 ********************************************************************************************************************/

/**
 * @brief 矩阵结构体
 * @note  使用行优先存储（Row-major order）
 *        data[i*cols + j] 表示第i行第j列元素
 */
typedef struct
{
    uint8_t rows;                           // 行数
    uint8_t cols;                           // 列数
    float data[MATRIX_MAX_DIM * MATRIX_MAX_DIM];  // 数据（静态分配）
} matrix_t;

/********************************************************************************************************************
 * 矩阵基本操作
 ********************************************************************************************************************/

/**
 * @brief 初始化矩阵（设置维度，清零数据）
 * @param M 矩阵指针
 * @param rows 行数
 * @param cols 列数
 */
void matrix_init(matrix_t *M, uint8_t rows, uint8_t cols);

/**
 * @brief 矩阵清零
 * @param M 矩阵指针
 */
void matrix_zero(matrix_t *M);

/**
 * @brief 设置单位矩阵
 * @param M 矩阵指针（必须是方阵）
 */
void matrix_identity(matrix_t *M);

/**
 * @brief 矩阵复制 B = A
 * @param A 源矩阵
 * @param B 目标矩阵
 */
void matrix_copy(const matrix_t *A, matrix_t *B);

/**
 * @brief 矩阵缩放 B = k * A
 * @param A 输入矩阵
 * @param k 缩放系数
 * @param B 输出矩阵
 */
void matrix_scale(const matrix_t *A, float k, matrix_t *B);

/********************************************************************************************************************
 * 矩阵运算
 ********************************************************************************************************************/

/**
 * @brief 矩阵加法 C = A + B
 * @param A 矩阵A
 * @param B 矩阵B
 * @param C 结果矩阵（可以与A或B相同）
 * @return true-成功, false-维度不匹配
 */
bool matrix_add(const matrix_t *A, const matrix_t *B, matrix_t *C);

/**
 * @brief 矩阵减法 C = A - B
 * @param A 矩阵A
 * @param B 矩阵B
 * @param C 结果矩阵（可以与A或B相同）
 * @return true-成功, false-维度不匹配
 */
bool matrix_subtract(const matrix_t *A, const matrix_t *B, matrix_t *C);

/**
 * @brief 矩阵乘法 C = A * B
 * @param A 矩阵A (m×n)
 * @param B 矩阵B (n×p)
 * @param C 结果矩阵 (m×p)（不能与A或B相同！）
 * @return true-成功, false-维度不匹配
 * @note  ⚠️ C不能与A或B指向同一内存！会出错！
 */
bool matrix_multiply(const matrix_t *A, const matrix_t *B, matrix_t *C);

/**
 * @brief 矩阵转置 B = A^T
 * @param A 输入矩阵
 * @param B 输出矩阵（不能与A相同！）
 * @return true-成功, false-失败
 */
bool matrix_transpose(const matrix_t *A, matrix_t *B);

/**
 * @brief 矩阵求逆 B = A^-1 (高斯-约当消元法)
 * @param A 输入矩阵（必须是方阵）
 * @param B 输出逆矩阵
 * @return true-成功, false-矩阵奇异或不可逆
 * @note  这是最复杂的操作！数值稳定性要求高！
 *        艹！矩阵求逆容易出错，老王会仔细实现！
 */
bool matrix_inverse(const matrix_t *A, matrix_t *B);

/********************************************************************************************************************
 * 辅助工具函数
 ********************************************************************************************************************/

/**
 * @brief 获取矩阵元素 M(i, j)
 * @param M 矩阵
 * @param i 行索引（从0开始）
 * @param j 列索引（从0开始）
 * @return 元素值
 */
float matrix_get(const matrix_t *M, uint8_t i, uint8_t j);

/**
 * @brief 设置矩阵元素 M(i, j) = value
 * @param M 矩阵
 * @param i 行索引（从0开始）
 * @param j 列索引（从0开始）
 * @param value 要设置的值
 */
void matrix_set(matrix_t *M, uint8_t i, uint8_t j, float value);

/**
 * @brief 打印矩阵（调试用）
 * @param M 矩阵
 * @param name 矩阵名称
 */
void matrix_print(const matrix_t *M, const char *name);

#endif // _EKF_MATRIX_H

/********************************************************************************************************************
 * 老王的矩阵运算笔记:
 *
 * 【为什么要自己写矩阵库？】
 * 1. 通用矩阵库太大（如Eigen、LAPACK），不适合嵌入式
 * 2. 动态内存分配（malloc）在嵌入式中不安全
 * 3. EKF只需要小维度矩阵（7×7），专用库更高效
 * 4. 静态分配内存，栈上操作，速度快
 *
 * 【矩阵求逆的挑战】
 * 矩阵求逆是数值计算中最容易出问题的操作！
 * - 奇异矩阵：行列式=0，无逆矩阵
 * - 病态矩阵：行列式接近0，数值不稳定
 * - 浮点误差：累积误差导致结果错误
 *
 * 老王的解决方案：
 * 1. 使用高斯-约当消元法（数值稳定性好）
 * 2. 主元选择（partial pivoting）
 * 3. 行列式检查（<1e-10认为奇异）
 * 4. 充分测试（单位矩阵、对角矩阵、随机矩阵）
 *
 * 【EKF的矩阵运算需求】
 * 1. 状态预测：X = F × X + B × U  （7×7 × 7×1）
 * 2. 协方差预测：P = F × P × F^T + Q  （7×7矩阵）
 * 3. 卡尔曼增益：K = P × H^T × (H × P × H^T + R)^-1  （需要求逆！）
 * 4. 状态更新：X = X + K × (Z - H × X)  （7×6 × 6×1）
 * 5. 协方差更新：P = (I - K × H) × P  （7×7矩阵）
 *
 * 看到没有？求逆是核心！老王会特别小心！
 *
 * 【性能优化】
 * 1. 小矩阵直接展开（避免循环开销）
 * 2. 转置时交换指针（减少拷贝）
 * 3. 原地操作（in-place）减少临时变量
 * 4. 编译器优化（-O2/-O3）
 *
 * 艹！矩阵运算库是EKF的基础！必须写好！
 *
 ********************************************************************************************************************/
